const express=require('express');
const multer=require('multer');
const path=require('path');
const fs=require('fs');
const {rateLimit}=require('express-rate-limit');
const {xacThuc,allowed,validateOrigin}=require('../middleware/baoVeRoutes');
const profile=require('../controllers/hoSoController');
const pass=require('../controllers/khoiPhucMatKhauController');
const accounts=require('../controllers/quanLyTaiKhoanController');
const category=require('../controllers/danhMucQuanTriController');
const uploadDir=path.join(__dirname,'../../uploads/avatars');fs.mkdirSync(uploadDir,{recursive:true});
const upload=multer({storage:multer.diskStorage({destination:uploadDir,filename:(req,file,cb)=>cb(null,require('crypto').randomBytes(16).toString('hex')+'.'+({ 'image/jpeg':'jpg','image/png':'png','image/webp':'webp'}[file.mimetype]||'bin'))}),fileFilter:(req,file,cb)=>cb(null,['image/jpeg','image/png','image/webp'].includes(file.mimetype)),limits:{fileSize:2*1024*1024}});
const protection=rateLimit({windowMs:15*60*1000,limit:10,standardHeaders:'draft-8',legacyHeaders:false});
const taiKhoan=express.Router();taiKhoan.use(validateOrigin);
taiKhoan.get('/ho-so',xacThuc,profile.thongTin);
taiKhoan.patch('/cua-toi',xacThuc,profile.capNhat);
taiKhoan.post('/doi-mat-khau',xacThuc,profile.doiMatKhau);
taiKhoan.post('/quen-mat-khau',protection,pass.requestReset);
taiKhoan.post('/dat-lai-mat-khau',protection,pass.reset);
taiKhoan.get('/dia-chi',xacThuc,profile.danhSachDiaChi);
taiKhoan.post('/dia-chi',xacThuc,profile.themDiaChi);
taiKhoan.put('/dia-chi/:id',xacThuc,profile.suaDiaChi);
taiKhoan.delete('/dia-chi/:id',xacThuc,profile.xoaDiaChi);
taiKhoan.patch('/dia-chi/:id/mac-dinh',xacThuc,profile.macDinh);
taiKhoan.post('/anh-dai-dien',xacThuc,(req,res,next)=>upload.single('anh')(req,res,err=>{if(err)return res.status(err.code==='LIMIT_FILE_SIZE'?413:400).json({success:false,message:'Ảnh chỉ hỗ trợ JPEG/PNG/WebP, tối đa 2MB.'});next()}),profile.anhDaiDien);
const admin=express.Router();admin.use(validateOrigin,xacThuc,allowed('Admin','Quản lý'));
admin.get('/tai-khoan',accounts.list);
admin.post('/tai-khoan',accounts.create);
admin.get('/tai-khoan/:id',accounts.detail);
admin.put('/tai-khoan/:id',accounts.update);
admin.patch('/tai-khoan/:id/trang-thai',accounts.status);
admin.delete('/tai-khoan/:id',accounts.remove);
// Aliases in the team's documented API (employee administration).
admin.get('/nhan-vien',(req,res,next)=>{req.query.vaiTro='Nhân viên';accounts.list(req,res,next)});
admin.post('/nhan-vien',(req,res,next)=>{req.body.vaiTro='Nhân viên';accounts.create(req,res,next)});
admin.put('/nhan-vien/:id',accounts.update);
admin.patch('/nhan-vien/:id/trang-thai',accounts.status);
admin.get('/khach-hang',(req,res,next)=>{req.query.vaiTro='Khách hàng';accounts.list(req,res,next)});
const danhMuc=express.Router();danhMuc.use(validateOrigin);
danhMuc.get('/',category.list);
danhMuc.get('/:id',category.detail);
danhMuc.post('/',xacThuc,allowed('Admin','Quản lý'),category.create);
danhMuc.put('/:id',xacThuc,allowed('Admin','Quản lý'),category.update);
danhMuc.delete('/:id',xacThuc,allowed('Admin','Quản lý'),category.remove);
danhMuc.patch('/thu-tu/sap-xep',xacThuc,allowed('Admin','Quản lý'),category.reorder);
module.exports={taiKhoan,admin,danhMuc,uploadDir};
