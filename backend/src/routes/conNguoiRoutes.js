const router=require("express").Router();
const {rateLimit}=require("express-rate-limit");
const {xacThuc,choPhepVaiTro}=require("../middleware/xacThuc");
const c=require("../controllers/conNguoiController");
const limiter=()=>rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false,message:{success:false,message:"Bạn thao tác quá nhiều lần. Vui lòng thử lại sau."}});
router.get("/thiet-lap",limiter(),c.setupInfo);
router.post("/thiet-lap",limiter(),c.setup);
router.use(xacThuc);
router.get("/toi",c.profile);
router.put("/toi",c.updateProfile);
router.patch("/toi/mat-khau",limiter(),c.changePassword);
router.use(choPhepVaiTro("Quản lý","Admin"));
router.use("/tai-khoan/:kind",(req,res,next)=>["khach-hang","nhan-vien"].includes(req.params.kind)?next():res.status(400).json({success:false,message:"Nhóm tài khoản không hợp lệ."}));
router.get("/tai-khoan/:kind",c.list);
router.post("/tai-khoan/:kind",c.create);
router.get("/tai-khoan/:kind/:id",c.detail);
router.put("/tai-khoan/:kind/:id",c.update);
router.patch("/tai-khoan/:kind/:id/trang-thai",c.status);
router.post("/tai-khoan/:kind/:id/lien-ket",c.invite);
module.exports=router;
